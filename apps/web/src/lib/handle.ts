/** A friendly handle derived from the address, the same on every device: "calm-otter-47". */
export function handleOf(address: string): string {
  const h = keccak256(toBytes(address.toLowerCase()));
  const n = (i: number) => parseInt(h.slice(2 + i * 2, 4 + i * 2), 16);
  return `${ADJ[n(0) % ADJ.length]}-${ANIMAL[n(1) % ANIMAL.length]}-${String(n(2) % 100).padStart(2, "0")}`;
}
