/* global fetch, console, AbortSignal, URL */
// Measured block time (not a claim) on Monad testnet and mainnet: blocks produced per second over a long window.
//   node scripts/numbers/chain-facts.mjs     writes docs/evidence/phase-10/chain-facts.md
import { writeFileSync } from "node:fs";
const rpc = async (url, method, params = []) =>
  (
    await (
      await fetch(url, {
        method: "POST",
        headers: { "content-type": "application/json" },
        body: JSON.stringify({ jsonrpc: "2.0", id: 1, method, params }),
        signal: AbortSignal.timeout(20000),
      })
    ).json()
  ).result;
const measure = async (name, url, back) => {
  const head = Number(BigInt(await rpc(url, "eth_blockNumber")));
  const a = await rpc(url, "eth_getBlockByNumber", ["0x" + (head - back).toString(16), false]);
  const b = await rpc(url, "eth_getBlockByNumber", ["0x" + head.toString(16), false]);
  const dt = Number(BigInt(b.timestamp) - BigInt(a.timestamp));
  return {
    name,
    url,
    head,
    back,
    seconds: dt,
    secPerBlock: dt / back,
    gasPriceGwei: Number(BigInt(await rpc(url, "eth_gasPrice"))) / 1e9,
    at: new Date().toISOString(),
  };
};
const rows = [
  await measure("Monad testnet", "https://rpc-testnet.monadinfra.com", 200_000),
  await measure("Monad mainnet", "https://rpc.monad.xyz", 200_000),
];
const md = [
  "# Measured block time on Monad",
  "",
  "Generated by `node scripts/numbers/chain-facts.mjs`. Method: block timestamps at the head and 200,000 blocks earlier; seconds per block = elapsed seconds / 200,000. Block timestamps have one-second resolution, so over this window the error is well under 0.001 s per block.",
  "",
  "| Chain | Head block | Window (blocks) | Elapsed (s) | Seconds per block | `eth_gasPrice` (gwei) | Measured at |",
  "|---|---:|---:|---:|---:|---:|---|",
  ...rows.map(
    (r) =>
      `| ${r.name} | ${r.head.toLocaleString("en-US")} | ${r.back.toLocaleString("en-US")} | ${r.seconds.toLocaleString("en-US")} | ${r.secPerBlock.toFixed(4)} | ${r.gasPriceGwei} | ${r.at} |`,
  ),
  "",
].join("\n");
writeFileSync(new URL("../../docs/evidence/phase-10/chain-facts.md", import.meta.url), md);
console.log(md);
