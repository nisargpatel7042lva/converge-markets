/* global fetch, console, AbortSignal, URL */
// Monad (measured) versus Ethereum mainnet (estimated) for what Converge's keeper pays.
//   node scripts/numbers/cost-comparison.mjs      writes docs/evidence/phase-10/cost-comparison.{json,md}
//
// MEASURED inputs (gas LIMITS the keeper sent on Monad testnet; Monad bills the limit): docs/evidence/phase-5/costs.md.
// The Kuru cancel-and-replace is from docs/evidence/phase-0/kuru-spike.md (mainnet eth_estimateGas, 554,734).
// LIVE inputs fetched now: Monad mainnet gas price, Ethereum mainnet gas price, ETH/USD (Coinbase), MON/USD (Chainlink
// proxy on Monad mainnet, feed 0xBcD78f76005B7515837af6b50c7C52BCf73822fb, 8 decimals).
// METHOD for Ethereum: the same operations use the same gas there, but Ethereum bills gas USED, not the limit. The
// keeper's limit is the estimate + 15 %, so used = limit / 1.15. cost = used x gasPrice x ETH/USD. This is an ESTIMATE:
// opcode costs match, but state-access costs and Kuru itself are not on Ethereum, so it prices the same bytecode work.
import { writeFileSync } from "node:fs";

const MEASURED = {
  setSigma: 53_076,
  executeOrder: 664_935,
  splitForInventory: 466_858,
  mergeInventory: 247_549,
  settleEpoch: 300_484,
  kuruRequote: 554_734,
};
const SIGMA_PER_ROUND = 1.5;
const ROUNDS_PER_DAY = 96;
const LIMIT_OVER_USED = 1.15;
const roundLimit =
  MEASURED.splitForInventory +
  MEASURED.mergeInventory +
  MEASURED.settleEpoch +
  SIGMA_PER_ROUND * MEASURED.setSigma;

const rpc = async (url, method, params = []) =>
  (
    await (
      await fetch(url, {
        method: "POST",
        headers: { "content-type": "application/json" },
        body: JSON.stringify({ jsonrpc: "2.0", id: 1, method, params }),
        signal: AbortSignal.timeout(15000),
      })
    ).json()
  ).result;

const monadGasWei = BigInt(await rpc("https://rpc.monad.xyz", "eth_gasPrice"));
const ethGasWei = BigInt(await rpc("https://ethereum-rpc.publicnode.com", "eth_gasPrice"));
const cb = await (
  await fetch("https://api.exchange.coinbase.com/products/ETH-USD/ticker", {
    signal: AbortSignal.timeout(10000),
  })
).json();
const ethUsd = Number(cb.price);
const feed = "0xBcD78f76005B7515837af6b50c7C52BCf73822fb";
const raw = await rpc("https://rpc.monad.xyz", "eth_call", [
  { to: feed, data: "0xfeaf968c" },
  "latest",
]);
const w = (i) => BigInt("0x" + raw.slice(2 + i * 64, 2 + (i + 1) * 64));
const monUsd = Number(w(1)) / 1e8;
const monUpdatedAt = Number(w(3));
const at = new Date().toISOString();

const monad = (gas) => ({
  mon: (gas * Number(monadGasWei)) / 1e18,
  usd: ((gas * Number(monadGasWei)) / 1e18) * monUsd,
});
const eth = (gas, gweiOverride) => {
  const wei = gweiOverride === undefined ? Number(ethGasWei) : gweiOverride * 1e9;
  const used = gas / LIMIT_OVER_USED;
  return { used: Math.round(used), usd: ((used * wei) / 1e18) * ethUsd };
};
const rows = [
  ["One volatility refresh (setSigma): what keeps the ladder current", MEASURED.setSigma],
  ["Serve one trade (executeOrder)", MEASURED.executeOrder],
  ["One Kuru cancel-and-replace two-sided quote (batchUpdate)", MEASURED.kuruRequote],
  ["One 15-minute round of maintenance (split + merge + settleEpoch + 1.5 refreshes)", roundLimit],
  ["One series-day (96 rounds)", roundLimit * ROUNDS_PER_DAY],
].map(([name, gas]) => ({
  name,
  gasLimit: Math.round(gas),
  monad: monad(gas),
  ethLive: eth(gas),
  eth1gwei: eth(gas, 1),
  eth10gwei: eth(gas, 10),
}));

const out = {
  generatedAt: at,
  inputs: {
    monadGasPriceGwei: Number(monadGasWei) / 1e9,
    ethereumGasPriceGwei: Number(ethGasWei) / 1e9,
    ethUsd,
    monUsd,
    monUsdFeedUpdatedAt: new Date(monUpdatedAt * 1000).toISOString(),
    limitOverUsed: LIMIT_OVER_USED,
    measuredGasLimits: MEASURED,
  },
  rows,
};
writeFileSync(
  new URL("../../docs/evidence/phase-10/cost-comparison.json", import.meta.url),
  JSON.stringify(out, null, 2) + "\n",
);
const f = (x, d = 6) => (x < 0.01 ? x.toFixed(d) : x.toFixed(4));
const md = [
  "# Monad versus Ethereum: what the keeper pays (measured on Monad, estimated for Ethereum)",
  "",
  `Generated by \`node scripts/numbers/cost-comparison.mjs\` at ${at}. Rerun it to refresh the live inputs.`,
  "",
  "## Inputs",
  "",
  "| Input | Value | Source |",
  "|---|---|---|",
  `| Monad mainnet gas price | ${out.inputs.monadGasPriceGwei} gwei | \`eth_gasPrice\` on https://rpc.monad.xyz, ${at} |`,
  `| Ethereum mainnet gas price | ${out.inputs.ethereumGasPriceGwei.toFixed(4)} gwei | \`eth_gasPrice\` on https://ethereum-rpc.publicnode.com, ${at} |`,
  `| ETH/USD | $${ethUsd} | Coinbase Exchange ticker, ${at} |`,
  `| MON/USD | $${monUsd} | Chainlink MON/USD on Monad mainnet (0xBcD7…22fb), updated ${out.inputs.monUsdFeedUpdatedAt} |`,
  "| Gas per operation | see below | `docs/evidence/phase-5/costs.md` (Monad testnet, gas limits sent) and `docs/evidence/phase-0/kuru-spike.md` (Kuru re-quote, mainnet `eth_estimateGas`) |",
  "",
  "## Method",
  "",
  "1. **Monad (measured).** Monad bills the gas **limit**. The keeper sends the estimate plus 15 %, so cost = gas limit x gas price x MON/USD.",
  `2. **Ethereum (estimated).** The same operations use the same gas on any EVM chain, but Ethereum bills gas **used**, which is the limit divided by ${LIMIT_OVER_USED}. cost = (limit / ${LIMIT_OVER_USED}) x gas price x ETH/USD.`,
  "3. **What this is not.** An estimate of the same bytecode work. Ethereum state-access pricing and Kuru itself (which is on Monad) are not modelled. Ethereum's live gas price is the number above; the 1 and 10 gwei columns are scenarios, not data, because Ethereum's gas price moves by orders of magnitude.",
  "",
  "## Result",
  "",
  "| Operation | Gas limit | Monad: MON | Monad: USD | Ethereum now: USD | Ethereum at 1 gwei: USD | Ethereum at 10 gwei: USD |",
  "|---|---:|---:|---:|---:|---:|---:|",
  ...rows.map(
    (r) =>
      `| ${r.name} | ${r.gasLimit.toLocaleString("en-US")} | ${f(r.monad.mon, 5)} | ${f(r.monad.usd)} | ${f(r.ethLive.usd)} | ${f(r.eth1gwei.usd)} | ${f(r.eth10gwei.usd)} |`,
  ),
  "",
].join("\n");
writeFileSync(new URL("../../docs/evidence/phase-10/cost-comparison.md", import.meta.url), md);
console.log(md);
